#!/usr/bin/env bash
# Full model × config matrix. Models run in parallel (Groq rate limits are per model),
# configs run serially within a model. Then builds evals/results/summary.md.
# Usage: [MAX_SAMPLES=1|3] evals/run_matrix.sh [epochs]   (default 3 epochs, MAX_SAMPLES=1: ~1.5 h; =3: ~1 h with retries)
set -euo pipefail
cd "$(dirname "$0")/.."
EPOCHS="${1:-3}"
mkdir -p evals/logs evals/results
MODELS=(qwen/qwen3.6-27b qwen/qwen3.8-27b openai/gpt-oss-20b openai/gpt-oss-120b)
pids=()
for model in "${MODELS[@]}"; do
  evals/run_model.sh "$model" "$EPOCHS" > "evals/results/run_${model//\//_}.log" 2>&1 &
  pids+=($!)
done
status=0
for pid in "${pids[@]}"; do wait "$pid" || status=1; done
uv run python evals/report.py
{ printf -- '---\ntitle: Eval report\n---\n\n'; cat evals/results/summary.md; } > docs/eval-report.md
{ printf -- '---\ntitle: Groq cost\n---\n\n# Groq cost: the eval matrix and a 150-student cohort\n\nGenerated by `uv run python evals/cost.py`. Prices are Groq list prices as of 2026-09 from a third-party summary; verify in the Groq console before budgeting. Tokens per request were measured on Titanic with the query-forcing template; wider student schemas cost more.\n\n'; uv run python evals/cost.py; } > docs/cost.md
exit $status
